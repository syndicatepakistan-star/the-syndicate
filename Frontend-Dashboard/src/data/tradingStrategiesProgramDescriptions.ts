function normalizeTitleKey(title: string): string {
  return title
    .toLowerCase()
    .replace(/[^a-z0-9\s&]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

export function tradingStrategiesTeaser(description: string): string {
  return extractProgrammeIntroductionTeaser(description);
}

export function curatedTradingStrategiesDescription(
  slug: string | null | undefined,
  title: string | null | undefined,
): string | undefined {
  const slugKey = slug?.trim().toLowerCase();
  if (slugKey && STRATEGIES_SLUG_TO_KEY[slugKey]) {
    return TRADING_STRATEGIES_PROGRAM_DESCRIPTIONS[STRATEGIES_SLUG_TO_KEY[slugKey]];
  }
  const titleKey = normalizeTitleKey(title ?? "");
  if (titleKey && STRATEGIES_TITLE_TO_KEY[titleKey]) {
    return TRADING_STRATEGIES_PROGRAM_DESCRIPTIONS[STRATEGIES_TITLE_TO_KEY[titleKey]];
  }
  return undefined;
}
